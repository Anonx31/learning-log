# Create a list of numbers from 1 to 5
list = [1, 2, 3, 4, 5]

# Calculate and print the sum of all elements in the list
# sum(list) adds all numbers: 1+2+3+4+5 = 15
print(f"Total of the list is {sum(list)}")

# Find and print the smallest element in the list
# min(list) returns the minimum value: 1
print(f"Minimum of the list is {min(list)}")

# Find and print the largest element in the list
# max(list) returns the maximum value: 5
print(f"Maximum of the list is {max(list)}")

# Find and print the average of the list
print(f"Average of the list is {sum(list) / len(list)}")