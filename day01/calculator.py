# Ask the user to enter the first number
num1 = int(input("Enter the first number: "))

# Ask the user to enter the second number
num2 = int(input("Enter the second number: "))

# Calculate the sum of both numbers
sum = num1 + num2

# Calculate the difference between both numbers
diff = num1 - num2

# Calculate the product of both numbers
prod = num1 * num2

# Display the sum of the two numbers
print(f"The sum of 2 numbers is {sum}.")

# Display the difference between the two numbers
print(f"The difference between two numbers is {diff}.")

# Display the product of the two numbers
print(f"The product of two numbers is {prod}.")